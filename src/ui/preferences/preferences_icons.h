#ifndef BONGO_CAT_PREFERENCES_ICONS_H
#define BONGO_CAT_PREFERENCES_ICONS_H

#include <stdbool.h>

#include "nuklear_config.h"

/*
 * 设置页用到的全部图标 (全部是代码画的矢量图形, 没有图片文件)。
 * 枚举值分成两段: 前面几个 SECTION_* 是段落标题用的大图标, 从
 * BONGO_CAT_PREF_ICON_MULTIPLE_MODELS 起是表单行用的小图标。分段依据是枚举顺序,
 * 两边的绘制函数按区间判断归属 —— 所以**新增图标必须加在所属段的末尾**, 插到中间
 * 会让后面所有图标的含义整体错位。
 * BONGO_CAT_PREF_ICON_COUNT 必须始终是最后一个。
 */
typedef enum BongoCatPrefIcon {
    BONGO_CAT_PREF_ICON_SECTION_WINDOW,
    BONGO_CAT_PREF_ICON_SECTION_MODEL,
    BONGO_CAT_PREF_ICON_SECTION_APPLICATION,
    BONGO_CAT_PREF_ICON_SECTION_APPEARANCE,
    BONGO_CAT_PREF_ICON_MULTIPLE_MODELS,
    BONGO_CAT_PREF_ICON_PASS_THROUGH,
    BONGO_CAT_PREF_ICON_ALWAYS_ON_TOP,
    BONGO_CAT_PREF_ICON_KEEP_IN_SCREEN,
    BONGO_CAT_PREF_ICON_SOLID_BACKGROUND,
    BONGO_CAT_PREF_ICON_WINDOW_SIZE,
    BONGO_CAT_PREF_ICON_WINDOW_CORNERS,
    BONGO_CAT_PREF_ICON_OPACITY,
    BONGO_CAT_PREF_ICON_RANDOM_EXPRESSION,
    BONGO_CAT_PREF_ICON_MIRROR,
    BONGO_CAT_PREF_ICON_MOUSE_MIRROR,
    BONGO_CAT_PREF_ICON_MOUSE_CENTERED,
    BONGO_CAT_PREF_ICON_IGNORE_MOUSE,
    BONGO_CAT_PREF_ICON_MAX_FPS,
    BONGO_CAT_PREF_ICON_AUTOSTART,
    BONGO_CAT_PREF_ICON_LANGUAGE,
    BONGO_CAT_PREF_ICON_THEME,
    BONGO_CAT_PREF_ICON_SHORTCUT_VISIBILITY,
    BONGO_CAT_PREF_ICON_SHORTCUT_PREFERENCES,
    BONGO_CAT_PREF_ICON_HIDE_FADE,
    BONGO_CAT_PREF_ICON_RENDERER,
    BONGO_CAT_PREF_ICON_FRAME_BOUNDS,
    BONGO_CAT_PREF_ICON_RANDOM_MOTION,
    BONGO_CAT_PREF_ICON_RANDOM_SOUND,
    BONGO_CAT_PREF_ICON_VERTICAL_FLIP,
    BONGO_CAT_PREF_ICON_MOUSE_VERTICAL_FLIP,
    /* 新增图标一律加在段末: 行图标总表按"枚举 - BONGO_CAT_PREF_ICON_MULTIPLE_MODELS"
       取下标 (见 preferences_row_icons.c), 插到中间会让后面所有图标的含义整体错位。 */
    BONGO_CAT_PREF_ICON_VSYNC,
    BONGO_CAT_PREF_ICON_COUNT
} BongoCatPrefIcon;

void bongo_cat_pref_icon_draw(struct nk_command_buffer *canvas,
    struct nk_rect bounds, BongoCatPrefIcon icon, struct nk_color color);

#endif